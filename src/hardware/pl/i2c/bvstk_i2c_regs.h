#ifndef BVSTK_PL_I2C_REGS_H
#define BVSTK_PL_I2C_REGS_H

#include <stdint.h>

#define BVSTK_I2C_SLV_CSR_OFFSET       UINT32_C(0x00)
#define BVSTK_I2C_SLV_IRQ_OFFSET       UINT32_C(0x04)
#define BVSTK_I2C_SLV_STATUS_OFFSET    UINT32_C(0x08)
#define BVSTK_I2C_SLV_TX_DATA_OFFSET   UINT32_C(0x0C)

#define BVSTK_I2C_MSTR_CSR_OFFSET      UINT32_C(0x00)
#define BVSTK_I2C_MSTR_IRQ_OFFSET      UINT32_C(0x04)
#define BVSTK_I2C_MSTR_TX_FIFO_OFFSET  UINT32_C(0x08)
#define BVSTK_I2C_MSTR_TIMEOUT_OFFSET  UINT32_C(0x0C)
#define BVSTK_I2C_MSTR_DBG0_OFFSET     UINT32_C(0x10)
#define BVSTK_I2C_MSTR_DBG1_OFFSET     UINT32_C(0x14)
#define BVSTK_I2C_MSTR_DBG2_OFFSET     UINT32_C(0x18)
#define BVSTK_I2C_MSTR_DBG3_OFFSET     UINT32_C(0x1C)

#define BVSTK_I2C_BRAM_MASTER_OFFSET   UINT32_C(0x0500)
#define BVSTK_I2C_BRAM_SLAVE_WR_OFFSET UINT32_C(0x0000)
#define BVSTK_I2C_BRAM_SLAVE_RD_OFFSET UINT32_C(0x1000)

#define BVSTK_I2C_MSTR_SOFT_RESET_BIT  (UINT32_C(1) << 0)
#define BVSTK_I2C_MSTR_START_BIT       (UINT32_C(1) << 1)

#endif /* BVSTK_PL_I2C_REGS_H */
