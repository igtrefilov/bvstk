#!/usr/bin/env python3
"""Generate the FreeRTOS built-in configuration header."""
from __future__ import annotations

import argparse
from pathlib import Path
import re


def c_escape_bytes(data: bytes) -> str:
    out: list[str] = []
    for b in data:
        if b == 0x5C:  # backslash
            out.append("\\\\")
        elif b == 0x22:  # quote
            out.append('\\"')
        elif b == 0x0A:
            out.append("\\n")
        elif b == 0x0D:
            out.append("\\r")
        elif 0x20 <= b <= 0x7E:
            out.append(chr(b))
        else:
            out.append(f"\\x{b:02x}")
    return "".join(out)


def c_ident_from_filename(name: str) -> str:
    path = Path(name)
    stem = path.parent.name if path.parent != Path(".") else path.stem
    s = re.sub(r"[^a-zA-Z0-9]+", "_", stem).strip("_")
    if not s:
        s = "I2C_DEVICE"
    if s[0].isdigit():
        s = "_" + s
    return s.upper()


def profile_files(directory: Path) -> list[tuple[str, bytes, str]]:
    # Only the device JSON is firmware configuration. Maps/views stay on
    # Flash.  A legacy */profile.json is accepted while source trees migrate
    # to the canonical */<device>.json name.
    candidates: dict[str, Path] = {}
    for p in directory.glob("*/*.json"):
        if p.name == "profile.json" or p.stem.lower() == p.parent.name.lower():
            candidates[p.parent.name.lower()] = p
    for p in directory.glob("*.json"):
        if p.name != "register_map.json" and not p.name.endswith("_register_map.json"):
            candidates.setdefault(p.stem.lower(), p)
    result = []
    for _, p in sorted(candidates.items()):
        data = p.read_bytes()
        result.append((p.relative_to(directory).as_posix(), data, c_escape_bytes(data)))
    return result


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo-root", required=True, help="Path to repo root (contains configs/)")
    ap.add_argument("--out", required=True, help="Output header path")
    ap.add_argument(
        "--i2c-only",
        action="store_true",
        help="Generate a compact header containing only I2C defaults",
    )
    args = ap.parse_args()

    repo_root = Path(args.repo_root).resolve()
    src_dir = repo_root / "configs"
    network_src = src_dir / "network.json"
    i2c_dir = src_dir / "i2c"
    mdio_dir = src_dir / "mdio"
    out = Path(args.out).resolve()

    net_data = network_src.read_bytes()
    net_escaped = c_escape_bytes(net_data)

    i2c_files = profile_files(i2c_dir)
    mdio_files = profile_files(mdio_dir)

    out.parent.mkdir(parents=True, exist_ok=True)
    parts: list[str] = []
    include_guard = (
        "BVSTK_I2C_DEFAULT_CONFIGS_H"
        if args.i2c_only
        else "BVSTK_FREERTOS_DEFAULT_CONFIGS_H"
    )
    parts.append(f"#ifndef {include_guard}\n")
    parts.append(f"#define {include_guard}\n\n")
    parts.append("/* Autogenerated by tools/codegen/gen_default_configs.py. */\n\n")
    if not args.i2c_only:
        parts.append(f"static const char DEFAULT_NETWORK_JSON[] = \"{net_escaped}\";\n")
        parts.append(f"static const unsigned int DEFAULT_NETWORK_JSON_LEN = {len(net_data)}u;\n\n")

    parts.append("typedef struct {\n")
    parts.append("    const char *file_name;\n")
    parts.append("    const char *json;\n")
    parts.append("    unsigned int json_len;\n")
    parts.append("} default_json_file_t;\n\n")

    default_entries: list[str] = []
    for fname, data, escaped in i2c_files:
        ident = c_ident_from_filename(fname)
        parts.append(f"static const char DEFAULT_I2C_{ident}_JSON[] = \"{escaped}\";\n")
        parts.append(f"static const unsigned int DEFAULT_I2C_{ident}_JSON_LEN = {len(data)}u;\n\n")
        default_entries.append(f"    {{ \"{fname}\", DEFAULT_I2C_{ident}_JSON, DEFAULT_I2C_{ident}_JSON_LEN }},\n")

    if not default_entries:
        parts.append("static const default_json_file_t DEFAULT_I2C_CONFIG_FILES[] = { };\n")
        parts.append("static const unsigned int DEFAULT_I2C_CONFIG_FILES_COUNT = 0u;\n\n")
    else:
        parts.append("static const default_json_file_t DEFAULT_I2C_CONFIG_FILES[] = {\n")
        parts.extend(default_entries)
        parts.append("};\n")
        parts.append(f"static const unsigned int DEFAULT_I2C_CONFIG_FILES_COUNT = {len(default_entries)}u;\n\n")

    if not args.i2c_only:
        mdio_default_entries: list[str] = []
        for fname, data, escaped in mdio_files:
            ident = c_ident_from_filename(fname)
            parts.append(f"static const char DEFAULT_MDIO_{ident}_JSON[] = \"{escaped}\";\n")
            parts.append(f"static const unsigned int DEFAULT_MDIO_{ident}_JSON_LEN = {len(data)}u;\n\n")
            mdio_default_entries.append(f"    {{ \"{fname}\", DEFAULT_MDIO_{ident}_JSON, DEFAULT_MDIO_{ident}_JSON_LEN }},\n")

        if not mdio_default_entries:
            parts.append("static const default_json_file_t DEFAULT_MDIO_CONFIG_FILES[] = { };\n")
            parts.append("static const unsigned int DEFAULT_MDIO_CONFIG_FILES_COUNT = 0u;\n\n")
        else:
            parts.append("static const default_json_file_t DEFAULT_MDIO_CONFIG_FILES[] = {\n")
            parts.extend(mdio_default_entries)
            parts.append("};\n")
            parts.append(f"static const unsigned int DEFAULT_MDIO_CONFIG_FILES_COUNT = {len(mdio_default_entries)}u;\n\n")

    parts.append(f"#endif /* {include_guard} */\n")

    out.write_text(
        "".join(parts),
        encoding="utf-8",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
